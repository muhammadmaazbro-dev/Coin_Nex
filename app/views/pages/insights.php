<script>
(function () {
    const body = document.getElementById('chat-body');
    const quick = document.getElementById('chat-quick');
    const input = document.getElementById('chat-q');
    const form = document.getElementById('chat-form');

    function addMsg(text, who) {
        const row = document.createElement('div');
        row.className = 'chat-msg ' + who;
        const b = document.createElement('div');
        b.className = 'chat-bubble';
        b.textContent = text;
        row.appendChild(b);
        body.appendChild(row);
        body.scrollTop = body.scrollHeight;
    }

    function ask(q) {
        addMsg(q, 'me');
        fetch('<?= Helper::url('insights/chat') ?>?q=' + encodeURIComponent(q))
            .then(r => r.json())
            .then(d => {
                addMsg(d.reply, 'bot');
                quick.innerHTML = '';
                (d.quick || []).forEach(c => {
                    const btn = document.createElement('button');
                    btn.className = 'chip';
                    btn.textContent = c;
                    btn.addEventListener('click', () => { ask(c); });
                    quick.appendChild(btn);
                });
            }).catch(() => addMsg('Sorry, I had trouble answering. Try again.', 'bot'));
    }

    form.addEventListener('submit', function (e) {
        e.preventDefault();
        const q = input.value.trim();
        if (!q) return;
        input.value = '';
        ask(q);
    });
    quick.querySelectorAll('.chip').forEach(btn => {
        btn.addEventListener('click', () => ask(btn.textContent.trim()));
    });
})();
</script>